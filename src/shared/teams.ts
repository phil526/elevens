export interface Attributes {
  pace: number;
  acceleration: number;
  stamina: number;
  control: number;
  passing: number;
  shooting: number;
  tackling: number;
  goalkeeping: number;
}

export interface PlayerDef {
  name: string;
  short: string;
  number: number;
  role: Role;
  attrs: Attributes;
  skin: number; // skin tone colour
  hair: number;
  foot?: 'R' | 'L'; // stronger foot (derived from the name when not set)
  weakFoot?: number; // weak-foot rating 1..5 stars (derived when not set)
}

/**
 * Stronger foot and weak-foot rating. Fixed per player and identical on every machine (derived
 * from the name unless the squad sets it): about one in five is left-footed, and weak-foot
 * ratings run from 2 to 5 stars. `weak` is 0..1, where 1 means both feet are as good.
 */
export function footProfile(def: PlayerDef): { foot: 1 | -1; stars: number; weak: number } {
  let h = 2166136261;
  for (let i = 0; i < def.name.length; i++) h = Math.imul(h ^ def.name.charCodeAt(i), 16777619);
  h >>>= 0;
  const foot = def.foot ? (def.foot === 'R' ? 1 : -1) : h % 100 < 21 ? -1 : 1;
  const roll = (h >>> 8) % 100;
  const stars = def.weakFoot ?? (roll < 25 ? 2 : roll < 70 ? 3 : roll < 93 ? 4 : 5);
  return { foot, stars, weak: (stars - 1) / 4 };
}

