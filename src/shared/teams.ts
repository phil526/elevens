/**
 * A club for the cup and league: each player's attributes come from their role, the club's
 * strength (-6 weaker .. +3 stronger than the two main clubs) and style, with a small fixed
 * per-player variation, so every machine builds the same squad.
 */
function makeClub(id: string, name: string, abbr: string, style: string, strength: number, flavour: Flavour, home: Kit, away: Kit, names: string[], numbers = [1, 2, 5, 6, 3, 4, 8, 10, 7, 9, 11]): TeamDef {
  const players = ROLES.map((role, i): PlayerDef => {
    const full = names[i];
    let h = 2166136261;
    for (let k = 0; k < full.length; k++) h = Math.imul(h ^ full.charCodeAt(k), 16777619);
    h >>>= 0;
    const base = ROLE_BASE[role], fl = FLAVOUR[flavour];
    const attrs = {} as Attributes;
    (Object.keys(base) as (keyof Attributes)[]).forEach((key, j) => {
      const vary = ((h >>> (j * 3)) % 7) - 3;
      const skip = key === 'goalkeeping' && role !== 'GK';
      attrs[key] = skip ? 10 : Math.max(30, Math.min(95, base[key] + strength + (fl[key] ?? 0) + vary));
    });
    return { name: full, short: full.split(' ').slice(1).join(' '), number: numbers[i], role, attrs, skin: SK[h % SK.length], hair: HR[(h >>> 5) % HR.length] };
  });
  return { id, name, abbr, style, home, away, players };
}

