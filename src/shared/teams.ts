const BENCH_FIRST = ['Tom', 'Leo', 'Sami', 'Kai', 'Ollie', 'Joel', 'Remy', 'Dev', 'Ilan', 'Marco', 'Finn', 'Arlo'];
const BENCH_LAST = ['Hale', 'Brennan', 'Okafor', 'Lindqvist', 'Varga', 'Moreau', 'Teague', 'Achebe', 'Sorensen', 'Pike', 'Ruiz', 'Doyle'];
/** Bench order: a keeper, then a defender, midfielder, winger and striker. */
export const BENCH_ROLES: Role[] = ['GK', 'RCB', 'RCM', 'RW', 'ST'];

/**
 * Five substitutes per club, generated from the club id so every machine has the same bench. Each is a
 * little weaker than the starter in that position but fresh, with numbers 12 to 16.
 */
export function benchFor(team: TeamDef): PlayerDef[] {
  if (team.bench && team.bench.length) return team.bench.slice(0, 7);
  let h = 2166136261;
  for (let i = 0; i < team.id.length; i++) h = Math.imul(h ^ team.id.charCodeAt(i), 16777619);
  h >>>= 0;
  const used = new Set(team.players.map((p) => p.short));
  return BENCH_ROLES.map((role, i) => {
    const base = team.players.find((p) => p.role === role)!.attrs;
    const d = 4 + ((h >>> (i * 3)) % 5);
    const s = (v: number) => Math.max(30, v - d);
    let k = 0, short = '';
    let first = '';
    do { first = BENCH_FIRST[(h + i * 5 + k) % BENCH_FIRST.length]; short = BENCH_LAST[((h >>> 4) + i * 7 + k * 3) % BENCH_LAST.length]; k++; } while (used.has(short) && k < 12);
    used.add(short);
    return {
      name: `${first} ${short}`, short, number: 12 + i, role,
      attrs: { pace: s(base.pace), acceleration: s(base.acceleration), stamina: Math.min(95, base.stamina + 2), control: s(base.control), passing: s(base.passing), shooting: s(base.shooting), tackling: s(base.tackling), goalkeeping: s(base.goalkeeping) },
      skin: SK[(h + i * 7) % SK.length], hair: HR[((h >>> 6) + i) % HR.length],
    };
  });
}

/** A player's card: overall rating for their position, and the six headline stats (0-99). */
export interface StatLine {
  ovr: number;
  pac: number; // pace and acceleration
  sho: number;
  pas: number;
  dri: number; // ball control
  def: number; // tackling
  sta: number; // stamina
  gk: number;
}

const ROLE_WEIGHTS: Record<'GK' | 'CB' | 'FB' | 'DM' | 'CM' | 'W' | 'ST', Partial<Record<keyof Attributes, number>>> = {
  GK: { goalkeeping: 0.82, passing: 0.08, acceleration: 0.1 },
  CB: { tackling: 0.45, pace: 0.12, stamina: 0.13, passing: 0.15, control: 0.15 },
  FB: { pace: 0.2, acceleration: 0.1, tackling: 0.28, stamina: 0.17, passing: 0.15, control: 0.1 },
  DM: { tackling: 0.32, passing: 0.3, stamina: 0.18, control: 0.2 },
  CM: { passing: 0.34, control: 0.26, shooting: 0.14, stamina: 0.14, tackling: 0.12 },
  W: { pace: 0.2, acceleration: 0.12, control: 0.3, shooting: 0.18, passing: 0.2 },
  ST: { shooting: 0.45, pace: 0.12, acceleration: 0.08, control: 0.25, passing: 0.1 },
};
const roleGroup = (r: Role) => (r === 'GK' ? 'GK' : r === 'RCB' || r === 'LCB' ? 'CB' : r === 'RB' || r === 'LB' ? 'FB' : r === 'CDM' ? 'DM' : r === 'RCM' || r === 'LCM' ? 'CM' : r === 'ST' ? 'ST' : 'W');

/** Overall rating and headline stats for a player in a position (their own by default). */
export function statLine(def: PlayerDef, role: Role = def.role): StatLine {
  const a = def.attrs;
  const w = ROLE_WEIGHTS[roleGroup(role)];
  let ovr = 0;
  for (const k of Object.keys(w) as (keyof Attributes)[]) ovr += a[k] * (w[k] ?? 0);
  return {
    ovr: Math.round(ovr), pac: Math.round((a.pace * 0.6 + a.acceleration * 0.4)), sho: a.shooting, pas: a.passing, dri: a.control, def: a.tackling, sta: a.stamina, gk: a.goalkeeping,
  };
}

/** A club's ratings by unit: attack (forwards), midfield, defence (back four and keeper), and overall. */
export function teamRatings(t: TeamDef): { att: number; mid: number; def: number; ovr: number } {
  const avg = (roles: Role[]) => Math.round(t.players.filter((p) => roles.includes(p.role)).reduce((s, p) => s + statLine(p).ovr, 0) / Math.max(1, roles.length));
  const att = avg(['RW', 'ST', 'LW']), mid = avg(['CDM', 'RCM', 'LCM']), def = avg(['GK', 'RB', 'RCB', 'LCB', 'LB']);
  return { att, mid, def, ovr: Math.round((att * 3 + mid * 3 + def * 5) / 11) };
}
